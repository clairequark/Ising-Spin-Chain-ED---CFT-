#= Generates the translationally invariant eigenstates of T. 

Schematic procedure: 

Act T on b until b returns to itself. 
IF value of b the smallest element in the set generated by T^r * b, then store the state and the period of the orbit into a list R_a. 


=# 

# Constructs basis states within a momentum sector. 
# R = -1 means not valid kernal. R = i gives the period of the orbit 


# Takes a bit mask, a bitstring, and a chain length; t is cyclically rotated on a PBC chain by one unit. 
# !! MASK MUST BE OF THE FORM OF A BITSTRING WITH ALL ONES !! 
function translate(t, N, mask)
    return ((t << 1) | (t >> (N - 1) )) & mask
end

