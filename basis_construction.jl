end


#= Crucial subroutine for translationally invariant basis construction
Determines orbital period for a bitstring s within a momentum sector k. Rejects s if it is not a kernal state. 
    INPUTS: 
    s - bitstring state
    k - crystal momentum sector to check within 
    params - contains size of spin chain 
    
    OUTPUT: 
    R - the orbital period 
    R = -1 if s is not a member of the crystal momentum block we are interested in. 
=#
function checkstate(s::Int,k::Int, params::ModelParams)
    N = params.N
    mask = (1 << N) - 1         # N bits of all 1's N = 3: 111 ; used to clear extra bits that pop up during translation
    t = s                       

    for i in 1:N
        t = translate(t, N, mask)

        if t<s                          # t < s implies that s is NOT the smallest element of its orbit (cannot be KERNAL state)
            return -1   
        elseif (t == s)                 # t == s implies that t is the MINIMUM element of its orbit (it IS the KERNAL state)
            if ((k % (N ÷ i)) != 0)     # compatibility condition for translationally invariant eigenstate; if violated, state is REJECTED
               return -1
            end
            return i                    # s is the kernal AND a compatible translationally invariant eigenstate
        end
    end

    return -1
end

#Stores the kernal and period of a translationally invariant eigenstate. 
struct MomentumState
    rep::Int        # kernel bitstring |b> 
    R::Int          # orbit period
end

#Stores momentum basis labeled by a momentum block k. 
struct MomentumBasis
    k::Int
    states::Vector{MomentumState}
    indexmap::Dict{Int,Int}         #maps rep -> basis index 
end


#=Generates the momentum basis states for a crystal momentum integer k and model defined by params. Uses checkstate to filter out compatible kernals.  
    INPUT: 
    k - crystal momentum integer 
    params - model params struct 

    OUTPUT: 
    MomentumBasis typed struct. Contains: 
                                        The momentum of the basis states. (k)
                                        Complete set of kernals and their orbital period. (states)
                                        (Dictionary) Lookup map between entry in states and the representative bitstring. 
                                        The dictionary takes in a kernal, and spits out the index in states for accessing the correct kernal and orbit period.

                                        Futue use of MomentumBasis might look like "for s in MomentumBasis.states, construct hamiltonian matrix element" 
                                        states is automatically sorted from least to greatest. 
=#
function build_momentum_basis(k::Int, params::ModelParams)
    N = params.N
    dim = 2^N 

    states = MomentumState[]
    indexmap = Dict{Int, Int}()

    for s in 0:(dim-1)
        
        R = checkstate(s, k, params)
        if R != -1

            push!(states, MomentumState(s, R))
            indexmap[s] = length(states)
        end
    end

    return MomentumBasis(k, states, indexmap)
end


#= 
I/O: 

I: bitstring 
O: kernal and # shifts needed to reach that kernal 
=#
function find_rep_and_shift(s::Int, params::ModelParams, mask::Int)
    rep = s 
    shift = 0 
    t = s 
    N = params.N

    for r in 1:N 
        t = ((t<<1) | (t >> (N-1))) & mask
        if t < rep
            rep = t 
            shift = r 
        end
        if t == s 
            break
        end 
    end
    return rep, shift
end


